// Builds the wallpapers: node scripts/build.mjs
// Writes hooks/walls.js (names, tones, glass), hooks/scenes.js (each scene's SVG and its picker card)
// and hooks/colors.js (each scene's window colours). `--only <key>` checks one scene without writing, and
// `--file <scene.mjs>` one scene module that isn't listed yet.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { limits, pastLimit } from './lib/limits.mjs'
import { look } from './lib/palette.mjs'
import { Scene } from './lib/scene.mjs'
import { SCENES as LISTED } from './scenes/index.mjs'

// what a plugin's Svg may hold
const LIMIT = 131072
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const arg = flag => (process.argv.includes(flag) ? process.argv[process.argv.indexOf(flag) + 1] : null)
const file = arg('--file')
const SCENES = file ? [(await import(join(process.cwd(), file))).default] : LISTED
const only = file ? SCENES[0].key : arg('--only')

const walls = [], scenes = {}, cards = {}, colors = {}
for (const def of SCENES) {
  if (only && def.key !== only) continue
  // seeded by its key, so a scene draws the same wherever it sits in the list
  const s = new Scene([...def.key].reduce((h, c) => Math.imul(h ^ c.charCodeAt(0), 16777619), 2166136261))
  def.build(s)
  const svg = s.svg(def.text)
  if (svg.length > LIMIT) throw new Error(`${def.key}: ${svg.length} characters, over the ${LIMIT} an Svg may hold`)
  const past = pastLimit(svg)
  if (past) throw new Error(`${def.key}: ${past.what} ${past.value} > ${past.most}; Claude Desktop would leave the scene out`)
  const { colors: theme, glass, problems } = look(def)
  scenes[def.key] = svg
  cards[def.key] = s.card()
  colors[def.key] = theme
  walls.push({ key: def.key, name: def.name, tone: def.tone, acc: def.accent, alt: def.alt, glass })
  const budget = limits(svg).map(l => `${l.what.split(' ')[0]} ${l.value}/${l.most}`).filter((_, i) => i === 1 || i === 4).join(', ')
  console.log(`${def.key.padEnd(11)} ${String(svg.length).padStart(6)} chars  card ${String(cards[def.key].length).padStart(5)}  ${budget}  ${problems.length} contrast notes`)
}

if (!only && !file) {
  const head = '// Generated by scripts/build.mjs. Do not edit by hand.\n'
  const keys = walls.map(w => `'${w.key}'`).join(' | ')
  writeFileSync(join(root, 'hooks/walls.js'), `${head}export const WALLS = ${JSON.stringify(walls)}\n`)
  writeFileSync(join(root, 'hooks/walls.d.ts'), `export type Key = ${keys}\nexport type Wall = { key: Key; name: string; tone: 'dark' | 'light'; acc: string; alt: string; glass: { blur: number; tint: string; opacity: number } }\nexport const WALLS: Wall[]\n`)
  writeFileSync(join(root, 'hooks/scenes.js'), `${head}export const SCENES = ${JSON.stringify(scenes)}\nexport const CARDS = ${JSON.stringify(cards)}\n`)
  writeFileSync(join(root, 'hooks/scenes.d.ts'), `import type { Key } from './walls.js'\nexport const SCENES: Record<Key, string>\nexport const CARDS: Record<Key, string>\n`)
  writeFileSync(join(root, 'hooks/colors.js'), `${head}export const COLORS = ${JSON.stringify(colors)}\n`)
  writeFileSync(join(root, 'hooks/colors.d.ts'), `import type { ThemeColors } from 'claude-code'\nimport type { Key } from './walls.js'\nexport const COLORS: Record<Key, ThemeColors>\n`)
}

// --preview <dir>: one HTML page per scene and per card, for a browser to screenshot
if (process.argv.includes('--preview')) {
  const dir = arg('--preview')
  for (const key of Object.keys(scenes)) {
    writeFileSync(join(dir, `${key}.html`), `<!doctype html><body style="margin:0;width:1600px;height:1000px;overflow:hidden;background:#000">${scenes[key]}</body>`)
    writeFileSync(join(dir, `${key}.card.html`), `<!doctype html><body style="margin:0;background:#222"><div style="width:256px;height:144px">${cards[key]}</div></body>`)
  }
}
